--   아래 5개 표준 지표로 통일한다. 신규 브랜드를 "도메인 선택"으로 생성하면
--   이 5축이 그 브랜드 pentagon_axes 로 복제된다(이후 브랜드 담당자가 본인 것 수정 가능).
--
--   1) 응대·표현          — 상담 매너·언어
--   2) 니즈파악·경청      — 무엇을 묻는지 정확히 파악
