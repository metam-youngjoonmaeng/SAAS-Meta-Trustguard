[출력] {"rating":"우수|보통|주의|실패","analysis":"핵심만 간결하게 2-3문장"}$p$),

    (4, '정확성·해결력',
     $desc$맞게 안내했고 실제로 해결했나 — 정확한 안내·오안내 방지, 금지멘트 준수, 복합문의 답변, 적극성·해결의지, 대안 제시·셀프서비스 안내, 절차 필수안내(반품·환불 소요일 등)$desc$,
