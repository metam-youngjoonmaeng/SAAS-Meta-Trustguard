def _agent_turn_text(call_id, line_no):
    """qa_conversations 의 turn_no(=line_no) 에 해당하는 상담사 발화 원문 반환."""
    if line_no is None:
        return None
    conv = CONVERSATIONS[call_id]
    if line_no < 1 or line_no > len(conv):
        raise ValueError(
            f"{call_id} line_no={line_no} 범위 밖 (총 {len(conv)} turns)"
        )
    sp, txt = conv[line_no - 1]
    if sp != "상담사":
        raise ValueError(
            f"{call_id} line_no={line_no} 상담사 발화 아님 (speaker={sp})"
        )
    return txt


def yn_record_for(call_id, item_no):
    """평가항목 1개 → (yn, detail_text, evidence_line_no, evidence_text).

    소비자보호부 평가발화는 위반(N) 행과 적합(Y) 행 모두 채워져야 한다
    (상세 페이지 '평가 발화' 컬럼이 빈 값으로 노출되지 않도록).
    누락 시 AssertionError 로 시드 빌드 실패 — 새 부서/콜 추가 시 동일 누락 재발 방지.
    """
    overrides = CONSUMER_YN.get(call_id, {})
    if item_no in overrides:
        return overrides[item_no]
    y_map = CONSUMER_Y_EVIDENCE.get(call_id) or {}
    if item_no not in y_map:
        raise AssertionError(
            f"{call_id} item_no={item_no} 평가발화 매핑 누락. "
            "CONSUMER_YN(위반) 또는 CONSUMER_Y_EVIDENCE(적합) 중 하나에 등록 필요."
        )
    line_no = y_map[item_no]
    return ("Y", None, line_no, _agent_turn_text(call_id, line_no))


