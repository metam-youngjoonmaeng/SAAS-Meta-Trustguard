- 주의: 본인확인 부실 또는 고지 누락 등 위험 소지
- 실패: 정보보호 위반·필수확인 미이행 등 중대한 규정 위반

[출력] {"rating":"우수|보통|주의|실패","analysis":"핵심만 간결하게 2-3문장"}$p$)
) AS a(axis_no, label, description, prompt_template)
