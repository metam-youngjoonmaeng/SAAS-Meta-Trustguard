    (domain_id, axis_no, label, description, prompt_template, is_active)
SELECT d.id, a.axis_no, a.label, a.description, a.prompt_template, true
FROM public.domains d
CROSS JOIN (VALUES
    (1, '응대·표현',
     $desc$상담 매너·언어 품질 — 첫인사(도입), 끝인사·추가문의 확인, 화답인사, 공감·호응·쿠션어, 정중한 언어표현$desc$,
     $p$[평가 축] 응대·표현 — 상담 매너와 언어 품질

