    (5, '컴플라이언스',
     $desc$규정준수·정보보호(규정·고객보호) — 본인확인 절차·순서·항목, 개인정보·정보보호·선언급 금지, 안내 범위 준수, 업무별 필수고지·상품 적합성, 보안사고 대응(분실·피싱·부정거래)$desc$,
