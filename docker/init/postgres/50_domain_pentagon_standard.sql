--   5) 컴플라이언스       — 규정준수·정보보호(규정·고객보호)
--
-- 모든 도메인에 동일 5축을 시드(CROSS JOIN domains). ON CONFLICT DO NOTHING 이라
--   이미 편집한 도메인 슬롯은 보존하고 빈 슬롯만 채운다(재기동 안전).
-- 현재 운영 DB 의 기존 도메인 축 교체는 별도 라이브 적용(DELETE 후 본 INSERT).
-- ============================================================

