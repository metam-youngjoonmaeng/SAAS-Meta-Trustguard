[출력] {"rating":"우수|보통|주의|실패","analysis":"핵심만 간결하게 2-3문장"}$p$),

    (3, '설명·전달력',
     $desc$얼마나 명확히 전달했나 — 설명력·전달력, 두괄식 전달, 내부용어·전문용어 지양$desc$,
     $p$[평가 축] 설명·전달력 — 안내를 얼마나 명확하게 전달했는가

