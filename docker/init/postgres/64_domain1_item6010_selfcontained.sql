[평가 대상] 이 상담의 업무유형을 먼저 정하고, 그 유형에 해당하는 아래 [참조 데이터] 체크리스트의 필수안내를 상담사가 이행했는지 대조한다. 상담사 발화만 이행 근거로 인정한다(고객 발화·조회결과 낭독은 이행 아님).

[판단 방법 — 반드시 이 순서(CoT)대로 생각한 뒤 점수를 정한다]
1) 업무유형 파악: 통화에서 다뤄진 업무유형(대분류>중분류)을 모두 식별한다. 고객이 명시 요청했거나 상담사가 실제 처리/안내한 업무는 전부 대상이다.
2) 트리거(적용조건) 성립 항목 선별: 식별된 업무유형에 해당하는 체크리스트 항목만 판정 대상으로 고른다.
   - 고지의무형(대출 상담의 연체 불이익·철회권, 수신상품의 중도해지·예금자보호 등)은 그 업무를 상담한 것만으로 성립한다(상황 미발생이어도 고지 의무).
   - 상황조건형(착오송금 발생, 보이스피싱 의심, 중복출금 등)은 그 상황이 실제 대화에 있을 때만 성립한다.
   - 본인확인 응답 발화(성함·생년월일 낭독)는 트리거가 아니다.
3) 요소별 이행 판정: 성립 항목마다 (필수요소: …)를 상담사 발화와 하나씩 대조해 [판정값]을 정한다. 근거는 통화 원문 발화를 그대로 인용하고, 없으면 미충족.
4) 점수 결정: 아래 [점수 기준]에 따라 12/6/0 중 하나로 정한다. 요소 확인을 건너뛰고 인상만으로 점수부터 정하지 말 것.

[판정값 정의] (요소·항목 단위)
- 충족   : 필수요소가 모두 상담사 발화에 의미적으로 존재(동의어·풀어쓴 표현 인정), 순서 요건 있으면 순서까지 충족.
- 부분   : 핵심요소는 전달했으나 부가 하위요소 1개 누락, 또는 경미하게 부정확(정정 불필요 수준).
- 미충족 : 트리거가 성립했는데 해당 안내를 전혀 하지 않음(필수요소 부재). 고객만 언급하고 상담사 안내가 없으면 미충족.
- 오안내 : 항목을 다뤘으나 사실과 다르거나 ✗ 미충족 예·금지멘트에 의미 매칭(원금보장·무조건 승인·즉시환급·즉시취소 단정 등). 일부 요소가 있어도 오안내가 우선(누락보다 중함).

[점수 기준] (12점 만점, 단계 [12 / 6 / 0]) — 판정루브릭 ③ #11 기준
- 12점 : 해당 업무유형의 필수·법정필수 항목이 전부 '충족'.
- 6점  : 부가(권장/부가 필수) 항목만 누락되고 핵심 필수는 모두 이행(부분 이행).
- 0점  : 법정필수 또는 핵심 필수 항목 1건 이상이 '미충족' 또는 '오안내'. (오안내 > 누락 — 둘 다면 오안내로 확정)
- ※ 업무유형은 어떤 상담이든 항상 존재하므로 이 항목은 N/A(해당없음)가 없다 — 반드시 12/6/0 중 하나로 채점한다.
- ※ 근거는 통화 원문 상담사 발화에서 그대로 인용. 없는 발화를 지어내면 그 요소는 미충족. 금액·금리·한도 수치는 STT 오인식을 감안해 검증한다.

